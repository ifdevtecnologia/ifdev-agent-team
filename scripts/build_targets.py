#!/usr/bin/env python3
"""Generates the per-tool files in `dist/` from the neutral sources in `core/` and `targets/`.

Inputs are read in sorted order and outputs use LF with no timestamps or absolute paths, so a
rerun on unchanged sources writes nothing. `--check` writes nothing and exits non-zero when a
generated file is missing or stale, or when `dist/` holds a file the generator does not produce.

Claude target:
- `dist/claude/CLAUDE.md` = `targets/claude/adapter.md` + `core/instructions.md`.
- `dist/claude/agents/<role>.md` = `core/agents/<role>.md` with its `read_only` frontmatter line
  replaced, in place, by the Claude tool lists, + `targets/claude/agent-footer.md`.
An empty adapter or footer adds nothing, so the output is then byte-identical to its source.

Codex target:
- `dist/codex/AGENTS.md` = `targets/codex/adapter.md` + `core/instructions.md` + every rule in
  `core/rules/` (sorted by name): Codex has no rules directory, so the rules travel inside the file.
- `dist/codex/agents/<role>.toml` = a generated-file comment and the TOML keys `name`,
  `description` and `developer_instructions` (the agent body, a read-only notice for read-only
  roles, which Codex does not enforce, and `targets/codex/agent-footer.md`).

Standard library only (Python 3.9+): the installer and CI need no extra dependency.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

DIST = "dist"
INSTRUCTIONS = "core/instructions.md"
AGENTS_DIR = "core/agents"
RULES_DIR = "core/rules"
CLAUDE_TARGET = "targets/claude"
CODEX_TARGET = "targets/codex"

# Every role reads, searches and runs commands; writers also edit files. Read-only roles block
# the edit tools explicitly, which Claude Code enforces.
CLAUDE_READ_ONLY_TOOLS = ("tools: Read, Glob, Grep, Bash", "disallowedTools: Write, Edit")
CLAUDE_WRITER_TOOLS = ("tools: Read, Glob, Grep, Bash, Write, Edit",)
READ_ONLY_VALUES = {"true": True, "false": False}
# Codex custom agents have no tool permissions, so a read-only role is read-only by instruction.
CODEX_READ_ONLY_NOTICE = (
    "This role is read-only, and Codex does not enforce it: do not create, edit or delete files, "
    "including through the shell, and report any file you changed."
)
CODEX_AGENT_HEADER = "# Generated by scripts/build_targets.py from {source}; do not edit.\n"
CODEX_AGENT_KEYS = ("name", "description")
TOML_SHORT_ESCAPES = {"\b": "\\b", "\t": "\\t", "\n": "\\n", "\f": "\\f", "\r": "\\r", '"': '\\"', "\\": "\\\\"}


class BuildError(Exception):
    """A source cannot be turned into its generated form."""


def join_sections(*sections: str) -> str:
    """Joins the non-empty sections with one blank line; empty sections add nothing."""
    present = [section for section in sections if section.strip()]
    if len(present) <= 1:
        return present[0] if present else ""
    return "\n\n".join(section.rstrip("\n") for section in present) + "\n"


def frontmatter_end(rel: str, lines: list[str]) -> int:
    """Index of the closing `---` of the frontmatter that opens <lines>."""
    if lines[0] != "---":
        raise BuildError(f"{rel}: missing frontmatter")
    try:
        return lines.index("---", 1)
    except ValueError:
        raise BuildError(f"{rel}: unterminated frontmatter") from None


def read_only_value(rel: str, value: str) -> bool:
    if value.strip() not in READ_ONLY_VALUES:
        raise BuildError(f"{rel}: 'read_only' must be true or false")
    return READ_ONLY_VALUES[value.strip()]


def claude_agent(rel: str, text: str, footer: str) -> str:
    """Replaces the neutral `read_only` frontmatter line with the Claude tool lists."""
    lines = text.split("\n")
    end = frontmatter_end(rel, lines)
    frontmatter: list[str] = []
    found = False
    for line in lines[1:end]:
        key, _, value = line.partition(":")
        if key != "read_only":
            frontmatter.append(line)
            continue
        if found:
            raise BuildError(f"{rel}: duplicate 'read_only' key")
        found = True
        frontmatter.extend(CLAUDE_READ_ONLY_TOOLS if read_only_value(rel, value) else CLAUDE_WRITER_TOOLS)
    if not found:
        raise BuildError(f"{rel}: missing 'read_only' key")
    agent = "\n".join([lines[0], *frontmatter, *lines[end:]])
    return join_sections(agent, footer)


def toml_string(value: str, multiline: bool = False) -> str:
    """Quotes <value> as a TOML basic string (multi-line when asked), escaping backslashes, quotes
    and every control character TOML does not allow literally. A multi-line string starts with a
    newline, which TOML trims, so the value is kept exactly."""
    escaped = []
    for char in value:
        if (char == "\n" and multiline) or char == "\t":
            escaped.append(char)
        elif char in TOML_SHORT_ESCAPES:
            escaped.append(TOML_SHORT_ESCAPES[char])
        elif ord(char) < 0x20 or ord(char) == 0x7F:
            escaped.append(f"\\u{ord(char):04X}")
        else:
            escaped.append(char)
    body = "".join(escaped)
    return f'"""\n{body}"""' if multiline else f'"{body}"'


def block_scalar(indicator: str, lines: list[str], index: int) -> tuple[str, int]:
    """Joins the indented (or blank) lines from <index> of a `>` (folded) or `|` (literal) block;
    returns the stripped value and the index of the first line after the block."""
    block = []
    while index < len(lines) and (lines[index][:1] in (" ", "\t") or not lines[index].strip()):
        block.append(lines[index].strip())
        index += 1
    return (" " if indicator == ">" else "\n").join(block).strip(), index


def quoted_scalar(rel: str, line: str, value: str) -> str:
    quote = value[0]
    if len(value) < 2 or value[-1] != quote or (quote == '"' and "\\" in value):
        raise BuildError(f"{rel}: unsupported quoted frontmatter value: {line!r}")
    return value[1:-1].replace("''", "'") if quote == "'" else value[1:-1]


def frontmatter_fields(rel: str, lines: list[str]) -> dict[str, str]:
    """Reads the top-level string values of a frontmatter block without a YAML library: plain,
    simply quoted and block (`>`, `|`) scalars. Anything else (flow collections, anchors, tags,
    escapes in double quotes) is refused; the validator checks the result against a YAML parser."""
    fields: dict[str, str] = {}
    index = 0
    while index < len(lines):
        line = lines[index]
        index += 1
        if not line.strip() or line.startswith("#"):
            continue
        key, separator, value = line.partition(":")
        value = value.strip()
        if not separator or not key or key != key.strip() or line[0].isspace() or value[:1] in ("[", "{", "&", "*", "!"):
            raise BuildError(f"{rel}: unsupported frontmatter line: {line!r}")
        if value[:1] in (">", "|"):
            value, index = block_scalar(value[0], lines, index)
        elif value[:1] in ("'", '"'):
            value = quoted_scalar(rel, line, value)
        if key in fields:
            raise BuildError(f"{rel}: duplicate '{key}' key")
        fields[key] = value
    return fields


def codex_agent(rel: str, text: str, footer: str) -> str:
    """Turns a neutral agent into a Codex custom agent TOML file."""
    lines = text.split("\n")
    end = frontmatter_end(rel, lines)
    fields = frontmatter_fields(rel, lines[1:end])
    for key in (*CODEX_AGENT_KEYS, "read_only"):
        if key not in fields:
            raise BuildError(f"{rel}: missing '{key}' key")
    notice = CODEX_READ_ONLY_NOTICE if read_only_value(rel, fields["read_only"]) else ""
    instructions = join_sections("\n".join(lines[end + 1 :]).lstrip("\n"), notice, footer)
    keys = [f"{key} = {toml_string(fields[key])}" for key in CODEX_AGENT_KEYS]
    keys.append(f"developer_instructions = {toml_string(instructions, multiline=True)}")
    return CODEX_AGENT_HEADER.format(source=rel) + "\n".join(keys) + "\n"


def read_text(root: Path, rel: str) -> str:
    path = root / rel
    if path.is_symlink() or not path.is_file():
        raise BuildError(f"{rel}: source is missing or is not a regular file")
    return path.read_bytes().decode("utf-8")


def source_names(root: Path, rel_dir: str) -> list[str]:
    """The sorted Markdown file names of a source directory."""
    directory = root / rel_dir
    if directory.is_symlink() or not directory.is_dir():
        raise BuildError(f"{rel_dir}: source directory is missing or is not a directory")
    return sorted(path.name for path in directory.glob("*.md"))


def expected_files(root: Path) -> dict[str, str]:
    """Returns every generated file as {path relative to the repository: content}."""
    instructions = read_text(root, INSTRUCTIONS)
    agents = {name: read_text(root, f"{AGENTS_DIR}/{name}") for name in source_names(root, AGENTS_DIR)}
    rules = [read_text(root, f"{RULES_DIR}/{name}") for name in source_names(root, RULES_DIR)]

    claude_footer = read_text(root, f"{CLAUDE_TARGET}/agent-footer.md")
    files = {f"{DIST}/claude/CLAUDE.md": join_sections(read_text(root, f"{CLAUDE_TARGET}/adapter.md"), instructions)}
    for name, text in agents.items():
        files[f"{DIST}/claude/agents/{name}"] = claude_agent(f"{AGENTS_DIR}/{name}", text, claude_footer)

    codex_footer = read_text(root, f"{CODEX_TARGET}/agent-footer.md")
    codex_adapter = read_text(root, f"{CODEX_TARGET}/adapter.md")
    files[f"{DIST}/codex/AGENTS.md"] = join_sections(codex_adapter, instructions, *rules)
    for name, text in agents.items():
        role = name[: -len(".md")]
        files[f"{DIST}/codex/agents/{role}.toml"] = codex_agent(f"{AGENTS_DIR}/{name}", text, codex_footer)
    return files


def existing_files(root: Path) -> set[str]:
    """Every path below dist/ that is not a directory (symlinks included, never followed)."""
    dist = root / DIST
    if dist.is_symlink():
        raise BuildError(f"{DIST}: must be a directory, not a symlink")
    found = set()
    for dirpath, dirnames, filenames in os.walk(dist):
        for name in filenames + [d for d in dirnames if (Path(dirpath) / d).is_symlink()]:
            found.add((Path(dirpath) / name).relative_to(root).as_posix())
    return found


def problems(root: Path) -> list[tuple[str, str]]:
    """Lists every missing, stale or extra file in dist/ as (path, problem) without writing anything."""
    expected = expected_files(root)
    existing = existing_files(root)
    found = []
    for rel, content in sorted(expected.items()):
        path = root / rel
        if rel not in existing:
            found.append((rel, "generated file is missing"))
        elif path.is_symlink() or path.read_bytes() != content.encode("utf-8"):
            found.append((rel, "generated file is stale"))
    found += [(rel, "file is not produced by the generator") for rel in sorted(existing - set(expected))]
    return found


def build(root: Path) -> list[str]:
    """Writes stale or missing files and removes extra ones; returns the changed paths."""
    expected = expected_files(root)
    changed = []
    for rel in sorted(existing_files(root) - set(expected)):
        (root / rel).unlink()
        changed.append(rel)
    for rel, content in sorted(expected.items()):
        path = root / rel
        data = content.encode("utf-8")
        if path.is_file() and not path.is_symlink() and path.read_bytes() == data:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.is_symlink():
            path.unlink()
        path.write_bytes(data)
        changed.append(rel)
    for dirpath, _, _ in sorted(os.walk(root / DIST), reverse=True):
        if Path(dirpath) != root / DIST and not os.listdir(dirpath):
            os.rmdir(dirpath)
    return changed


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="report stale or extra files without writing")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        if args.check:
            found = problems(root)
            for rel, problem in found:
                print(f"ERROR {rel}: {problem}")
            print("build_targets: STALE (run python3 scripts/build_targets.py)" if found else "build_targets: OK")
            return 1 if found else 0
        for rel in build(root):
            print(f"updated: {rel}")
        print("build_targets: OK")
        return 0
    except BuildError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
